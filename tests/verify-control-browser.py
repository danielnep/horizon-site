import asyncio
import hashlib
import json
import os
from pathlib import Path
import urllib.request
from playwright.async_api import async_playwright

BASE='https://horizonsolucoes.com/central'
OUT=Path('/opt/horizon-panel-control-20261101/evidence')
OUT.mkdir(exist_ok=True)


def get(path):
    with urllib.request.urlopen(BASE+'/api/'+path,timeout=30) as response:
        return json.load(response)


async def main():
    overview=get('overview')
    assert overview['available']['vps'] and len(overview['agents'])==18
    target='ctl-a6f99840ae6e4bc499b5'
    receipt=get('tasks/'+target+'/details')
    assert receipt['commands'] and receipt['evidence']
    item=receipt['evidence'][0]
    with urllib.request.urlopen(BASE+'/api/tasks/'+target+'/evidence/'+str(item['index']),timeout=30) as response:
        raw=response.read();assert response.headers.get_content_type()=='image/png'
    assert hashlib.sha256(raw).hexdigest()==item['sha256']
    (OUT/'actual-ronda-proof.png').write_bytes(raw)
    errors=[];screens=[]
    async with async_playwright() as p:
        browser=await p.chromium.launch(headless=True,args=['--no-sandbox'])
        for name,width,height in [('mobile',412,915),('desktop',1440,960)]:
            page=await browser.new_page(viewport={'width':width,'height':height},device_scale_factor=1)
            page.on('pageerror',lambda e:errors.append(str(e)))
            await page.goto(BASE+'/#tarefas',wait_until='domcontentloaded')
            button=page.locator('[data-detail="'+target+'"]')
            await button.wait_for(state='visible',timeout=30000)
            await button.click()
            panel=page.locator('[data-proof-task="'+target+'"]')
            await panel.locator('summary').first.click()
            proof=panel.locator('[data-receipt-body]')
            await proof.get_by_role('heading',name='Capturas reais · '+str(len(receipt['evidence']))).wait_for(timeout=30000)
            # Receipts can grow during verification. The first capture remains stable.
            image=proof.locator('img').first
            await image.wait_for(state='visible')
            await image.evaluate('(img)=>img.decode()')
            assert await image.evaluate('(img)=>img.naturalWidth>0')
            assert await proof.locator('.command-receipts').count()==1
            assert await page.locator('body').evaluate('(el)=>el.scrollWidth<=innerWidth+2')
            path=OUT/('panel-evidence-'+name+'.png')
            await image.scroll_into_view_if_needed()
            await page.screenshot(path=str(path),full_page=False)
            screens.append(str(path))
            # Open the actual image using the link generated by the panel.
            async with page.expect_popup() as event:
                await proof.locator('.evidence-image').first.click()
            popup=await event.value
            await popup.wait_for_load_state('domcontentloaded')
            assert '/evidence/' in popup.url
            await popup.close()
            await page.close()
        await browser.close()
    assert not errors,errors
    report={'live':True,'url':BASE+'/','agents':18,'task':target,'commands':len(receipt['commands']),
        'real_evidence':len(receipt['evidence']),'image_sha256_verified':item['sha256'],
        'mobile_and_desktop_clicks':True,'popup_image_opened':True,'javascript_errors':errors,'screenshots':screens}
    (OUT/'control-verification.json').write_text(json.dumps(report,indent=2))
    print(json.dumps(report))


if __name__=='__main__':asyncio.run(main())
